describe("Synthesised implicit grouping",function()
	local groups=require("Modules.CraftingSynthesisGroups")
	it("groups real modifiers without requiring a unique tier identity",function()
		local result=groups.resolve({{line="+10 to Strength"},{line="+20 to Dexterity"}},data.itemMods.Synthesis)
		assert.equal(2,#result);assert.equal("+10 to Strength",result[1][1].line);assert.equal("+20 to Dexterity",result[2][1].line)
	end)
	it("rejects ambiguous or unknown line boundaries",function()
		local lines={{line="A"},{line="B"}}
		assert.is_nil(groups.resolve(lines,{{"A"},{"B"},{"A","B"}}))
		assert.is_nil(groups.resolve(lines,{{"A"}}))
		lines[1].modGroup="one";lines[2].modGroup="one"
		local result=groups.resolve(lines,{{"A"},{"B"},{"A","B"}})
		assert.equal(1,#result);assert.equal(2,#result[1])
	end)
	it("only reports targets that agree across possible identities and rolls",function()
		local group={candidates={{id="a",range=0.9},{id="b",range=0.2}}}
		assert.is_nil(groups.targetStatus(group,{anyOf={"a"}}))
		assert.is_true(groups.targetStatus(group,{anyOf={"a","b"}}))
		assert.is_nil(groups.targetStatus(group,{anyOf={"a","b"},minRoll=0.5}))
		assert.is_false(groups.targetStatus(group,{anyOf={"a","b"},fractured=true}))
	end)
	it("uses an exact imported range to resolve overlapping candidates",function()
		local modifiers={a={"+(1-10) to maximum Life"},b={"+(3-12) to maximum Life"}}
		local advanced=groups.resolve({{line="+(1-10) to maximum Life",range=0.37}},modifiers)
		assert.equal(1,#advanced[1].candidates);assert.equal("a",advanced[1].candidates[1].id)
		assert.equal(0.37,advanced[1].candidates[1].range)
		assert.is_true(groups.targetStatus(advanced[1],{anyOf={"a"},minRoll=0.35}))
		assert.is_false(groups.targetStatus(advanced[1],{anyOf={"a"},minRoll=0.4}))
		local plain=groups.resolve({{line="+4 to maximum Life"}},modifiers)
		assert.equal(2,#plain[1].candidates)
		assert.is_nil(groups.targetStatus(plain[1],{anyOf={"a"}}))
		local fixed=groups.resolve({{line="+4 to maximum Life"}},{a={"+4 to maximum Life"},b={"+(1-10) to maximum Life"}})
		assert.equal(2,#fixed[1].candidates)
		local same=groups.resolve({{line="+(1-10) to maximum Life",range=0.37}},{a={"+(1-10) to maximum Life"},b={"+(1-10) to maximum Life"}})
		assert.equal(2,#same[1].candidates)
	end)
end)

describe("Manual socket layout",function()
	local sim=require("Modules.CraftingSimulator")
	it("sets colours and links without changing the original or consuming currency",function()
		newBuild()
		local model=sim.model("Rarity: NORMAL\nPlate Vest\nItem Level: 86\nSockets: R-G B")
		local before=copyTable(model.initial);local saved
		local controls=require("Classes.CraftingSocketControl").Open(model,model.initial,function(state) saved=state end)
		controls.count:SelByValue(4,"val");controls.color1:SelByValue("W","val");controls.color2:SelByValue("B","val");controls.color3:SelByValue("R","val");controls.color4:SelByValue("G","val")
		controls.link2:Click();controls.use:Click()
		assert.same(before,model.initial);assert.is_not_nil(saved)
		assert.same({{color="W",group=0},{color="B",group=0},{color="R",group=0},{color="G",group=1}},saved.sockets)
		local reopened=sim.model(sim.toItem(model,saved).raw);assert.same(saved.sockets,reopened.initial.sockets)
		local checkpoint=require("Modules.CraftingCheckpoint").validate(model.raw,require("Modules.CraftingInventory").run(saved));assert.same(saved.sockets,checkpoint.state.sockets)
		main.popups={}
	end)
	it("round-trips an explicitly empty layout",function()
		newBuild()
		local model=sim.model("Rarity: NORMAL\nIron Hat\nItem Level: 86\nSockets: R-G")
		local saved;local controls=require("Classes.CraftingSocketControl").Open(model,model.initial,function(state) saved=state end)
		controls.count:SelByValue(0,"val");controls.use:Click();assert.same({},saved.sockets)
		assert.same({},sim.model(sim.toItem(model,saved).raw).initial.sockets)
		main.popups={}
	end)
	it("preserves Abyss sockets and rejects links to them",function()
		newBuild()
		local model=sim.model("Rarity: NORMAL\nStygian Vise\nItem Level: 86\nSockets: A")
		local saved;local controls=require("Classes.CraftingSocketControl").Open(model,model.initial,function(state) saved=state end)
		controls.color1:SelByValue("W","val");controls.use:Click();assert.is_nil(saved)
		main.popups={}
		local armour=sim.model("Rarity: NORMAL\nPlate Vest\nItem Level: 86\nSockets: A W")
		controls=require("Classes.CraftingSocketControl").Open(armour,armour.initial,function(state) saved=state end)
		controls.link1:Click();controls.use:Click();assert.is_nil(saved)
		main.popups={}
	end)
end)

describe("Genesis planning",function()
	local genesis=require("Modules.GenesisPlanner")
	it("allocates connected branches from the correct free womb",function()
		local tree=genesis.tree()
		for _,entry in ipairs({{19625,41240,"Currency"},{22476,33919,"Equipment"},{47967,28988,"Unique"},{42956,7411,"Mysterious"}}) do
			assert.equal(entry[3],genesis.roots[entry[1]]);assert.equal(entry[3].." Item Womb",tree.nodes[entry[2]].name);assert.equal(entry[1],tree.nodes[entry[2]].root)
		end
		local plan=genesis.empty();plan=genesis.toggle(plan,19912);plan=genesis.toggle(plan,53412)
		assert.equal(2,genesis.report(plan).counts[19625].allocated)
		assert.is_false(pcall(genesis.toggle,genesis.empty(),53412))
		assert.is_false(pcall(genesis.toggle,plan,41240))
		local reduced,removed=genesis.toggle(plan,19912);assert.same({19912,53412},removed);assert.equal(0,#reduced.nodes)
	end)
	it("requires a connected choice and replaces its previous option",function()
		local plan=genesis.empty()
		for _,id in ipairs({24821,10821,44677,10578}) do plan=genesis.toggle(plan,id) end
		assert.same({10578},genesis.report(plan).missingChoices)
		plan=genesis.toggle(plan,3839);assert.equal(0,#genesis.report(plan).missingChoices)
		plan=genesis.toggle(plan,4731);local set={};for _,id in ipairs(plan.nodes) do set[id]=true end
		assert.is_nil(set[3839]);assert.is_true(set[4731]);assert.equal(1,genesis.report(plan).counts[22476].options)
		assert.is_false(pcall(genesis.validate,{version=genesis.version,nodes={24821,10821,44677,10578,3839,4731}}))
		local reduced,removed=genesis.toggle(plan,10578);assert.same({4731,10578},removed);assert.equal(3,#reduced.nodes)
	end)
	it("connects a selected destination without mutating the original plan",function()
		local original=genesis.empty();local connected,path=genesis.connect(original,40721)
		assert.equal(0,#original.nodes);assert.is_true(#path>1);assert.equal(40721,path[#path]);assert.same(connected,genesis.validate(connected))
		local withChoice,choicePath=genesis.connect(original,3839)
		assert.equal(3839,choicePath[#choicePath]);assert.equal(0,#genesis.report(withChoice).missingChoices)
		assert.is_false(pcall(genesis.connect,connected,40721))
	end)
	it("preserves Genesis allocations in a saved Atlas plan",function()
		newBuild();local atlas=require("Modules.AtlasPlanner");local g=genesis.toggle(genesis.empty(),19912)
		local plan={id="genesis-test",title="Genesis test",version=atlas.defaultVersion(build.spec.treeVersion),budget=10,nodes={},notes="",genesis=g}
		local store=build.savers.AtlasPlans;store:Upsert(plan);local xml={};store:Save(xml)
		local reopened=atlas.new(build);reopened:Load(xml)
		assert.is_nil(reopened.warning);assert.same(g,reopened.plans[1].genesis)
		local imported=atlas.import(atlas.export(plan));assert.same(g,imported.genesis)
		local ruthless=copyTable(plan);ruthless.version="3.30.0c-ruthless";assert.is_false(pcall(atlas.validate,ruthless))
		local old=copyTable(plan);old.version="3.29.3";assert.is_false(pcall(atlas.validate,old))
	end)
	it("shows Genesis allocations during AI proposal review",function()
		newBuild();local atlas=require("Modules.AtlasPlanner");local bridge=require("Modules.DesktopBuildBridge")
		local plan={id="genesis-review",title="Genesis review",version="3.30.0c",budget=10,nodes={},notes="",genesis=genesis.toggle(genesis.empty(),19912)}
		local prepared=bridge.prepare(build,{mode="edit",title="Genesis review",baseRevision=bridge.revision(build),operations={{type="set_atlas_plan",plan=plan}}})
		local changes=table.concat(prepared.changes," ");assert.is_truthy(changes:find("Genesis [3.30.0d]",1,true));assert.is_truthy(changes:find("Currency: Additional Currency Chance",1,true))
	end)
	it("navigates from Atlas tools, edits the tree and keeps the plan",function()
		for _,width in ipairs({960,1024,1280}) do
			newBuild();main.popups={};local ui=require("Modules.HeadlessUI").install({width=width,height=768})
			local ok,err=pcall(function()
				ui:bind(build)
				local atlas=require("Modules.AtlasPlanner");local plan={id="genesis-ui",title="Genesis UI",version="3.30.0c",budget=10,nodes={},notes=""}
				require("Classes.AtlasPlannerControl").Open(build,plan)
				ui:click("tools");ui:text("search","Genesis");ui:click("choose")
				assert.equal("Genesis tree",main.popups[1].title)
				local c=main.popups[1].controls;ui:text("search","Mutation Cultivation")
				local rx,ry=c.results:GetPos();ui:clickAt(rx+20,ry+12);assert.equal(40721,c.canvas.focus)
				ui:click("fit");ui:frame()
				local x,y=c.canvas:GetPos();local nx,ny=c.canvas:Position(c.canvas.tree.nodes[19912]);ui:clickAt(x+nx,y+ny)
				assert.equal(19912,c.canvas.focus);ui:click("toggle");ui:click("keep");ui:click("keep")
				local saved=build.savers.AtlasPlans.plans[1];assert.equal("3.30.0d",saved.genesis.version);assert.same({19912},saved.genesis.nodes)
			end)
			ui:restore();main.popups={};assert(ok,err)
		end
	end)
	it("confirms a searched path before adding its passives",function()
		newBuild();main.popups={};local ui=require("Modules.HeadlessUI").install({width=1024,height=768});local kept
		local ok,err=pcall(function()
			ui:bind(build);local c=require("Classes.GenesisPlannerControl").Open(nil,function(value) kept=value end)
			ui:text("search","Mutation Cultivation");local x,y=c.results:GetPos();ui:clickAt(x+20,y+12)
			assert.equal(40721,c.canvas.focus);ui:click("toggle");assert.equal("Connect Genesis path",main.popups[1].title)
			ui:click("confirm");ui:click("keep");assert.is_not_nil(kept)
			local found=false;for _,id in ipairs(kept.nodes) do if id==40721 then found=true end end;assert.is_true(found)
		end)
		ui:restore();main.popups={};assert(ok,err)
	end)
	it("finds passives in other branches and switches the tree",function()
		newBuild();main.popups={};local ui=require("Modules.HeadlessUI").install({width=960,height=640})
		local ok,err=pcall(function()
			ui:bind(build);local c=require("Classes.GenesisPlannerControl").Open(nil,function() end)
			assert.equal(19625,c.canvas.root);ui:text("search","Parthenogenesis")
			assert.equal("Mysterious tree",c.results.list[1].subtitle)
			local x,y=c.results:GetPos();ui:clickAt(x+20,y+12)
			assert.equal(48216,c.canvas.focus);assert.equal(42956,c.canvas.root);assert.equal(42956,c.branch:GetSelValueByKey("val"))
		end)
		ui:restore();main.popups={};assert(ok,err)
	end)
	it("switches a Genesis choice through the native controls",function()
		newBuild();main.popups={};local ui=require("Modules.HeadlessUI").install({width=1024,height=768});local kept
		local ok,err=pcall(function()
			ui:bind(build);local c=require("Classes.GenesisPlannerControl").Open(nil,function(value) kept=value end)
			ui:choose("branch",22476,"val")
			local function find(name)
				ui:text("search",name);local x,y=c.results:GetPos();ui:clickAt(x+20,y+12)
			end
			find("Increased Attack Modifier Chance");assert.equal(3839,c.canvas.focus);ui:click("toggle");ui:click("confirm")
			find("Increased Caster Modifier Chance");assert.equal(4731,c.canvas.focus);ui:click("toggle")
			assert.equal("Replace Genesis choice",main.popups[1].title)
			local cancel;for key,control in pairs(main.popups[1].controls) do if control.label=="Cancel" then cancel=key end end
			assert.is_not_nil(cancel);ui:click(cancel);ui:click("keep")
			local original={};for _,id in ipairs(kept.nodes) do original[id]=true end;assert.is_true(original[3839]);assert.is_nil(original[4731])
			c=require("Classes.GenesisPlannerControl").Open(kept,function(value) kept=value end);ui:choose("branch",22476,"val")
			find("Increased Caster Modifier Chance");ui:click("toggle");assert.equal("Replace Genesis choice",main.popups[1].title);ui:click("confirm");ui:click("keep")
			local selected={};for _,id in ipairs(kept.nodes) do selected[id]=true end;assert.is_nil(selected[3839]);assert.is_true(selected[4731])
		end)
		ui:restore();main.popups={};assert(ok,err)
	end)
	it("explains why Standard Genesis data is unavailable on a Ruthless Atlas",function()
		newBuild();main.popups={};local ui=require("Modules.HeadlessUI").install({width=1024,height=768})
		local ok,err=pcall(function()
			ui:bind(build);local plan={id="ruthless",title="Ruthless",version="3.30.0c-ruthless",budget=10,nodes={},notes=""}
			require("Classes.AtlasPlannerControl").Open(build,plan);ui:click("tools");ui:text("search","Genesis")
			local browser=main.popups[1].controls;assert.equal("genesis",browser.results.list[1].entry.id);ui:click("choose");assert.equal("Genesis tree unavailable",main.popups[1].title)
		end)
		ui:restore();main.popups={};assert(ok,err)
	end)
end)

-- cspell:ignore RGBW
describe("Copied loot-filter items",function()
	local clipboard=require("Modules.LootFilterClipboard")
	local parser=require("Modules.LootFilterParser")
	it("keeps missing equipment socket data unknown",function()
		local raw="Item Class: Helmets\nRarity: Rare\nFoe Visage\nIron Hat\n--------\nItem Level: 86"
		local missing=clipboard.parse(raw);assert.is_nil(missing.Sockets);assert.is_nil(missing.SocketGroup);assert.is_nil(missing.SocketColours);assert.is_nil(missing.LinkedSockets)
		for _,condition in ipairs({"Sockets = 0","SocketGroup RGB","LinkedSockets >= 1"}) do
			assert.equal("unknown",parser.simulate(parser.parse("Hide\n "..condition.."\nShow"),missing).status,condition)
		end
		local empty=clipboard.parse(raw.."\nSockets: 0");assert.equal(0,empty.Sockets);assert.equal(0,empty.LinkedSockets)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n Sockets = 0\nShow"),empty).action)
		local special=clipboard.parse(raw.."\nSockets: A-R-G W");assert.equal(4,special.Sockets);assert.equal("A RG W",special.SocketGroup);assert.equal(2,special.LinkedSockets)
		assert.has_error(function() clipboard.parse(raw.."\nSockets: unknown") end)
		assert.has_error(function() clipboard.parse(raw.."\nSockets: R--G") end)
	end)
	it("reads an explicit memory-strand value without assuming a missing one",function()
		local raw="Item Class: Helmets\nRarity: Rare\nFoe Visage\nIron Hat\n--------\nItem Level: 86"
		local rules=parser.parse("Hide\n MemoryStrands >= 60\nShow")
		local observed=clipboard.parse(raw.."\nMemory Strands: 75")
		assert.equal(75,observed.MemoryStrands);assert.equal("Hide",parser.simulate(rules,observed).action)
		local unknown=clipboard.parse(raw);assert.is_nil(unknown.MemoryStrands);assert.equal("unknown",parser.simulate(rules,unknown).status)
		assert.has_error(function() clipboard.parse(raw.."\nMemory Strands: 101") end)
		assert.has_error(function() clipboard.parse(raw.."\nMemory Strands: 5\nMemory Strands: 75") end)
	end)
	it("rejects conflicting copied socket layouts and gem levels",function()
		local helmet="Item Class: Helmets\nRarity: Normal\nIron Hat\n--------\n"
		local repeated=clipboard.parse(helmet.."Sockets: R-G  B\nSockets: R-G B")
		assert.equal(3,repeated.Sockets);assert.equal(2,repeated.LinkedSockets)
		assert.has_error(function() clipboard.parse(helmet.."Sockets: R-G B\nSockets: R G-B") end)
		assert.has_error(function() clipboard.parse(helmet.."Sockets: 0\nSockets: R") end)
		local gem="Item Class: Active Skill Gems\nRarity: Gem\nFireball\n--------\n"
		local item=clipboard.parse(gem.."Level: 20 (Max)\nLevel: 20");assert.equal(20,item.GemLevel)
		assert.has_error(function() clipboard.parse(gem.."Level: 1\nLevel: 20") end)
		assert.has_error(function() clipboard.parse(gem.."Level: 9999999999999999999999999999999999999999999999999999999999") end)
	end)
	it("retains explicitly marked unidentified item tiers without inventing missing tiers",function()
		local raw="Item Class: Helmets\nRarity: Rare\nFoe Visage\nIron Hat\n--------\nItem Level: 86\n--------\n"
		local item=clipboard.parse(raw.."Unidentified (Tier 4)")
		assert.is_false(item.Identified);assert.equal(4,item.UnidentifiedItemTier)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n Identified False\n UnidentifiedItemTier >= 4\nShow"),item).action)
		assert.equal("unknown",parser.simulate(parser.parse('Show\n HasExplicitMod "Life"\nHide'),item).status)
		local plain=clipboard.parse(raw.."Unidentified");assert.is_false(plain.Identified);assert.is_nil(plain.UnidentifiedItemTier)
		local unsupported=clipboard.parse(raw.."Unidentified (Tier 9)");assert.is_false(unsupported.Identified);assert.is_nil(unsupported.UnidentifiedItemTier)
		local text=clipboard.parse(raw.."Unidentified (Tier 4) modifier text");assert.is_true(text.Identified);assert.is_nil(text.UnidentifiedItemTier)
		assert.has_error(function() clipboard.parse(raw.."Unidentified (Tier 4)\nUnidentified (Tier 5)") end)
	end)
	it("reads visible equipment properties without inventing hidden modifier identities",function()
		local item=clipboard.parse("Item Class: Helmets\nRarity: Rare\nFoe Visage\nIron Hat\n--------\nQuality: +20% (augmented)\nSockets: R-G-B W\nItem Level: 86\n--------\nUnidentified\nCorrupted",72)
		assert.equal("Iron Hat",item.BaseType);assert.equal("Helmets",item.Class);assert.equal(20,item.Quality);assert.equal(4,item.Sockets);assert.equal("RGBW",item.SocketColours);assert.equal(3,item.LinkedSockets);assert.equal(72,item.AreaLevel)
		assert.equal(1,item.DropLevel);assert.equal(2,item.Width);assert.equal(2,item.Height)
		assert.is_false(item.Identified);assert.is_true(item.Corrupted);assert.is_nil(item.HasExplicitMod);assert.is_nil(item.FracturedItem)
		local numeric=parser.parse("Show\n Sockets >= 4").rules[1].conditions[1];local colors=parser.parse("Show\n Sockets RGB").rules[1].conditions[1]
		assert.is_true(parser.condition(numeric,item));assert.is_true(parser.condition(colors,item))
	end)
	it("accepts currency stacks and rejects unrelated clipboard text",function()
		local item=clipboard.parse("Item Class: Stackable Currency\nRarity: Currency\nChaos Orb\n--------\nStack Size: 7/20",83)
		assert.equal("Chaos Orb",item.BaseType);assert.equal(7,item.StackSize);assert.equal("Normal",item.Rarity)
		assert.equal(0,item.Sockets);assert.equal(0,item.LinkedSockets)
		assert.equal(12,item.DropLevel);assert.equal(1,item.Width);assert.equal(1,item.Height)
		assert.equal(0,item.BaseDefencePercentile)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n DropLevel >= 10\nShow"),item).action)
		assert.is_false(pcall(clipboard.parse,"some other clipboard text"));assert.is_false(pcall(clipboard.parse,"Rarity: Magic\nImaginary Unknown Base\n--------"))
	end)
	it("leaves an incomplete identified item's base unknown",function()
		local rule=parser.parse('Hide\n BaseType "Leather Belt"\nShow')
		for _,rarity in ipairs({"Rare","Unique","Relic"}) do
			local item=clipboard.parse("Rarity: "..rarity.."\nAn Unknown Name\n--------")
			assert.is_nil(item.BaseType);assert.is_nil(item.Class)
			assert.equal("unknown",parser.simulate(rule,item).status)
		end
		local explicit=clipboard.parse("Item Class: Skill Gems\nRarity: Unique\nAn Unknown Name\n--------")
		assert.is_nil(explicit.BaseType);assert.equal("Skill Gems",explicit.Class)
		local unidentified=clipboard.parse("Rarity: Rare\nUnknown Base\n--------\nUnidentified")
		assert.equal("Unknown Base",unidentified.BaseType)
		local complete=clipboard.parse("Rarity: Unique\nExample Name\nUnknown Base\n--------")
		assert.equal("Unknown Base",complete.BaseType)
	end)
	it("uses known clipboard and base classes for items without sockets",function()
		local cases={{"Gold","Gold"},{"Contracts","Contract: Bunker"},{"Blueprints","Blueprint: Bunker"},{"Expedition Logbooks","Expedition Logbook"}}
		local rule=parser.parse("Hide\n Sockets = 0\n BaseDefencePercentile = 0\nShow")
		for _,case in ipairs(cases) do
			local item=clipboard.parse("Item Class: "..case[1].."\nRarity: Normal\n"..case[2].."\n--------")
			assert.equal(case[1],item.Class);assert.equal(0,item.Sockets);assert.equal(0,item.LinkedSockets);assert.equal(0,item.BaseDefencePercentile)
			assert.equal("Hide",parser.simulate(rule,item).action)
		end
		for _,case in ipairs({{"Gold","Gold"},{"Expedition Logbook","Expedition Logbooks"},{"Ancient Wombgift","Wombgifts"}}) do
			local item=clipboard.parse("Rarity: Normal\n"..case[1].."\n--------")
			assert.equal(case[2],item.Class,case[1])
		end
		local rare=clipboard.parse("Rarity: Rare\nFoe Visage\nIron Hat\n--------\nItem Level: 86");assert.equal("Helmets",rare.Class)
		local ambiguous=clipboard.parse("Rarity: Normal\nPrimitive Chaotic Resonator\n--------");assert.is_nil(ambiguous.Class);assert.is_nil(ambiguous.Sockets)
		local explicit=clipboard.parse("Item Class: Delve Socketable Currency\nRarity: Normal\nPrimitive Chaotic Resonator\n--------");assert.equal("Delve Socketable Currency",explicit.Class)
		assert.equal(0,explicit.BaseDefencePercentile);assert.is_nil(explicit.Sockets)
		local unknownUnique=clipboard.parse("Rarity: Unique\nThe Fortunate\n--------");assert.is_nil(unknownUnique.Class)
	end)
	it("derives only known base-defence percentiles for copied items",function()
		local rules=parser.parse("Hide\n BaseDefencePercentile >= 40\nShow")
		local ring=clipboard.parse("Item Class: Rings\nRarity: Normal\nIron Ring\n--------\nItem Level: 10")
		assert.equal(100,ring.BaseDefencePercentile);assert.equal("Hide",parser.simulate(rules,ring).action)
		local armour=clipboard.parse("Item Class: Body Armours\nRarity: Normal\nVaal Regalia\n--------\nItem Level: 86")
		assert.is_nil(armour.BaseDefencePercentile);assert.equal("unknown",parser.simulate(rules,armour).status)
		local unique=clipboard.parse("Item Class: Rings\nRarity: Unique\nExample\nIron Ring\n--------\nItem Level: 86")
		assert.is_nil(unique.BaseDefencePercentile)
		local map=clipboard.parse("Item Class: Maps\nRarity: Normal\nBeach Map\n--------\nMap Tier: 1")
		assert.equal(0,map.BaseDefencePercentile);assert.equal("Show",parser.simulate(rules,map).action)
		local unknown=clipboard.parse("Item Class: Unknown Items\nRarity: Normal\nUnknown Example\n--------")
		assert.is_nil(unknown.BaseDefencePercentile)
	end)
	it("requires whole-line state markers and rejects non-finite visible numbers",function()
		local raw="Item Class: Helmets\nRarity: Normal\nIron Hat\n--------\nItem Level: 86\nCorrupted Blood cannot be inflicted on you"
		assert.is_false(clipboard.parse(raw).Corrupted)
		assert.is_false(pcall(clipboard.parse,raw:gsub("Item Level: 86","Item Level: "..string.rep("9",400))))
	end)
	it("reads visible cluster passive counts and enchantment markers",function()
		local raw="Item Class: Jewels\nRarity: Rare\nDragon Wound\nLarge Cluster Jewel\n--------\nItem Level: 84\n--------\nAdds 8 Passive Skills (enchant)\n2 Added Passive Skills are Jewel Sockets (enchant)\nAdded Small Passive Skills grant: 12% increased Damage (enchant)"
		local item=clipboard.parse(raw,83);assert.equal(8,item.EnchantmentPassiveNum);assert.is_true(item.AnyEnchantment)
		local rule=parser.parse('Show\n Class == "Jewels"\n EnchantmentPassiveNum = 8\n AnyEnchantment True\nHide')
		local result=parser.simulate(rule,item);assert.equal("matched",result.status);assert.equal("Show",result.action)
		local unresolved=clipboard.parse(raw:gsub("Adds 8 Passive Skills %(enchant%)","Adds 8 Passive Skills"),83)
		assert.is_nil(unresolved.EnchantmentPassiveNum);assert.is_true(unresolved.AnyEnchantment);assert.equal("unknown",parser.simulate(rule,unresolved).status)
		local absent=clipboard.parse("Item Class: Jewels\nRarity: Normal\nLarge Cluster Jewel\n--------")
		assert.is_nil(absent.AnyEnchantment);assert.is_nil(absent.EnchantmentPassiveNum)
		local ordinary=clipboard.parse("Item Class: Helmets\nRarity: Normal\nIron Hat\n--------\nAdds 8 Passive Skills (enchant)")
		assert.is_nil(ordinary.EnchantmentPassiveNum);assert.is_true(ordinary.AnyEnchantment)
		assert.has_error(function() clipboard.parse(raw.."\nAdds 9 Passive Skills (enchant)") end)
		assert.has_error(function() clipboard.parse(raw:gsub("Adds 8 Passive Skills","Adds "..string.rep("9",400).." Passive Skills")) end)
	end)
	it("reads numeric properties only from their own lines",function()
		local raw="Item Class: Helmets\nRarity: Normal\nIron Hat\n--------\nGrants Quality: +20%\nRequires Item Level: 86"
		local item=clipboard.parse(raw)
		assert.is_nil(item.Quality);assert.is_nil(item.ItemLevel)
		assert.equal("unknown",parser.simulate(parser.parse("Hide\n Quality >= 20\nShow"),item).status)
		local observed=clipboard.parse(raw.."\nQuality: +20% (augmented)\nItem Level: 86")
		assert.equal(20,observed.Quality);assert.equal(86,observed.ItemLevel)
		assert.has_error(function() clipboard.parse(raw.."\nItem Level: 86\nItem Level: 50") end)
	end)
	it("reads tier and named quality from current ordinary map items",function()
		local rules=parser.parse("Hide\n MapTier >= 5\n Quality >= 20\nShow")
		for _,header in ipairs({"Rarity: Normal\nMap (Tier 5)","Rarity: Magic\nEnlarged Map (Tier 5) of Flames","Rarity: Rare\nVortex Artifice\nMap (Tier 5)"}) do
			local raw="Item Class: Maps\n"..header.."\n--------\nQuality (Pack Size): +20% (augmented)\n--------\nItem Level: 68"
			local item=clipboard.parse(raw);assert.equal("Map (Tier 5)",item.BaseType);assert.equal(5,item.MapTier);assert.equal(20,item.Quality)
			assert.equal("Hide",parser.simulate(rules,item).action)
			assert.has_error(function() clipboard.parse(raw.."\nMap Tier: 6") end)
			assert.has_error(function() clipboard.parse(raw.."\nQuality: +15%") end)
		end
		local old=clipboard.parse("Item Class: Maps\nRarity: Normal\nStrand Map\n--------\nMap Tier: 5")
		assert.equal(5,old.MapTier);assert.is_nil(old.Quality)
		local unknown=clipboard.parse("Item Class: Maps\nRarity: Normal\nStrand Map\n--------")
		assert.is_nil(unknown.MapTier)
		assert.equal("unknown",parser.simulate(rules,unknown).status)
	end)
	it("uses explicitly marked implicit modifiers without assuming missing ones",function()
		local raw="Item Class: Rings\nRarity: Normal\nIron Ring\n--------\nItem Level: 10"
		local rule=parser.parse("Hide\n HasImplicitMod True\nShow")
		local missing=clipboard.parse(raw);assert.is_nil(missing.HasImplicitMod);assert.equal("unknown",parser.simulate(rule,missing).status)
		local marked=clipboard.parse(raw.."\nAdds 1 to 4 Physical Damage to Attacks (implicit)")
		assert.is_true(marked.HasImplicitMod);assert.equal("Hide",parser.simulate(rule,marked).action)
		assert.is_nil(clipboard.parse(raw.."\n(implicit) modifier text").HasImplicitMod)
	end)
	it("uses advanced modifier names as partial evidence",function()
		local raw='Item Class: Belts\nRarity: Rare\nTest Belt\nCord Belt\n--------\nItem Level: 86\n--------\n{ Prefix Modifier "Hale" (Tier: 1) }\n+100 to maximum Life\n{ Suffix Modifier "of Adaption" (Tier: 2) }\n+30% to Cold Resistance'
		local item=clipboard.parse(raw);assert.same({"Hale","of Adaption"},item.KnownExplicitMods);assert.is_nil(item.HasExplicitMod)
		local function result(condition) return parser.simulate(parser.parse("Hide\n "..condition.."\nShow"),item) end
		assert.equal("Hide",result('HasExplicitMod "Hale"').action)
		assert.equal("unknown",result('HasExplicitMod "Unknown"').status)
		assert.equal("Show",result('HasExplicitMod ! "Hale"').action)
		assert.equal("unknown",result('HasExplicitMod ! "Unknown"').status)
		assert.equal("Hide",result('HasExplicitMod >=2 "Hale" "of Adaption"').action)
		assert.equal("Show",result('HasExplicitMod <2 "Hale" "of Adaption"').action)
		assert.equal("unknown",result('HasExplicitMod >=3 "Hale" "of Adaption"').status)
		item.HasExplicitMod={};assert.equal("Show",result('HasExplicitMod "Hale"').action)
		assert.is_nil(clipboard.parse(raw.."\nUnidentified").KnownExplicitMods)
	end)
	it("recognizes twice-corrupted items as corrupted without guessing from modifier text",function()
		local raw="Item Class: Helmets\nRarity: Normal\nIron Hat\n--------\nItem Level: 86"
		local twice=clipboard.parse(raw.."\nTwice Corrupted")
		assert.is_true(twice.Corrupted);assert.is_true(twice.TwiceCorrupted)
		local once=clipboard.parse(raw.."\nCorrupted");assert.is_true(once.Corrupted);assert.is_false(once.TwiceCorrupted)
		local plain=clipboard.parse(raw.."\nTwice Corrupted modifiers");assert.is_false(plain.Corrupted);assert.is_false(plain.TwiceCorrupted)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n Corrupted True\n TwiceCorrupted True\nShow"),twice).action)
	end)
	it("reads influence markers on ordinary equipment without inferring unique or map influence",function()
		local raw="Item Class: Helmets\nRarity: Rare\nFoe Visage\nIron Hat\n--------\nItem Level: 86"
		local both=clipboard.parse(raw.."\nShaper Item\nElder Item")
		assert.same({"Shaper","Elder"},both.HasInfluence);assert.is_true(both.ShaperItem);assert.is_true(both.ElderItem)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n HasInfluence Elder\n ShaperItem True\nShow"),both).action)
		local none=clipboard.parse(raw.."\nShaper Item modifier text");assert.same({"None"},none.HasInfluence);assert.is_false(none.ShaperItem)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n HasInfluence None\n ElderItem False\nShow"),none).action)
		local unique=clipboard.parse("Item Class: Helmets\nRarity: Unique\nGoldrim\nLeather Cap\n--------\nItem Level: 86")
		assert.is_nil(unique.HasInfluence);assert.is_nil(unique.ShaperItem);assert.is_nil(unique.DropLevel)
		assert.equal("unknown",parser.simulate(parser.parse("Hide\n DropLevel >= 10\nShow"),unique).status)
		local map=clipboard.parse("Item Class: Maps\nRarity: Normal\nStrand Map\n--------\nMap Tier: 1")
		assert.is_nil(map.HasInfluence);assert.is_nil(map.ElderItem)
		local ambiguous=clipboard.parse("Item Class: Maps\nRarity: Normal\nBeach Map\n--------\nMap Tier: 1")
		assert.is_nil(ambiguous.DropLevel);assert.equal(1,ambiguous.Width);assert.equal(1,ambiguous.Height)
		local unknown=clipboard.parse("Item Class: Maps\nRarity: Normal\nUnknown Example Map\n--------\nMap Tier: 1")
		assert.is_nil(unknown.DropLevel);assert.is_nil(unknown.Width);assert.is_nil(unknown.Height)
	end)
	it("normalizes copied gem classes to the filter language",function()
		for label,class in pairs({["Active Skill Gems"]="Skill Gems",["Support Skill Gems"]="Support Gems"}) do
			local item=clipboard.parse("Item Class: "..label.."\nRarity: Gem\nAdded Fire Damage Support\n--------\nLevel: 12\nQuality: +20%",70)
			assert.equal(class,item.Class);assert.equal(12,item.GemLevel)
			assert.equal("matched",parser.simulate(parser.parse('Show\n Class == "'..class..'"\n Quality >= 1'),item).status)
		end
	end)
	it("recognizes known copied transfigured gems while leaving unknown variants uncertain",function()
		local function gem(name) return clipboard.parse("Item Class: Active Skill Gems\nRarity: Gem\n"..name.."\n--------\nLevel: 20") end
		local transfigured=gem("Fireball of Radiation");assert.equal("Fireball",transfigured.TransfiguredGem)
		assert.equal("Hide",parser.simulate(parser.parse('Hide\n TransfiguredGem "Fireball"\nShow'),transfigured).action)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n TransfiguredGem True\nShow"),transfigured).action)
		local ordinary=gem("Fireball");assert.is_false(ordinary.TransfiguredGem)
		assert.equal("Show",parser.simulate(parser.parse("Hide\n TransfiguredGem True\nShow"),ordinary).action)
		local unknown=gem("Fireball of an Unknown Future Variant");assert.is_nil(unknown.TransfiguredGem)
		assert.equal("unknown",parser.simulate(parser.parse("Hide\n TransfiguredGem True\nShow"),unknown).status)
		local vaal=gem("Vaal Fireball");assert.is_nil(vaal.TransfiguredGem)
	end)

	it("recognizes fractured and synthesised item markers without guessing absent flags",function()
		local raw="Item Class: Helmets\nRarity: Rare\nFoe Visage\nIron Hat\n--------\nItem Level: 86\nUnidentified"
		local fracture=clipboard.parse(raw.."\nFractured Item");assert.is_true(fracture.FracturedItem);assert.is_false(fracture.Identified)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n FracturedItem True\nShow"),fracture).action)
		local synth=clipboard.parse(raw.."\nSynthesised Item");assert.is_true(synth.SynthesisedItem)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n SynthesisedItem True\nShow"),synth).action)
		local plain=clipboard.parse(raw.."\nFractured Item text\nSynthesised Item text");assert.is_nil(plain.FracturedItem);assert.is_nil(plain.SynthesisedItem)
		assert.equal("unknown",parser.simulate(parser.parse("Hide\n FracturedItem True\nShow"),plain).status)
		assert.equal("unknown",parser.simulate(parser.parse("Hide\n SynthesisedItem True\nShow"),plain).status)
	end)

	it("does not mistake player-written notes for modifier markers",function()
		local raw="Item Class: Helmets\nRarity: Rare\nFoe Visage\nIron Hat\n--------\nItem Level: 86"
		for marker,condition in pairs({implicit="HasImplicitMod",enchant="AnyEnchantment",fractured="FracturedItem"}) do
			local item=clipboard.parse(raw.."\n--------\nNote: keep this ("..marker..")")
			assert.is_nil(item.HasImplicitMod);assert.is_nil(item.AnyEnchantment);assert.is_nil(item.FracturedItem)
			assert.equal("unknown",parser.simulate(parser.parse("Hide\n "..condition.." True\nShow"),item).status)
		end
		local fractured=clipboard.parse(raw.."\n+100 to maximum Life (fractured)")
		assert.is_true(fractured.FracturedItem)
	end)

end)

describe('Same-base vendor review',function()
 local vendor=require('Modules.VendorBaseSets')
 local function item(rarity,header,class) return 'Item Class: '..(class or 'Amulets')..'\nRarity: '..rarity..'\n'..header..'\n--------\nItem Level: 60' end
 local normal=item('Normal','Jade Amulet');local magic=item('Magic','Jade Amulet of the Lynx');local rare=item('Rare','Doom Beads\nJade Amulet');local unique=item('Unique','Karui Ward\nJade Amulet')
 before_each(function() newBuild() end)
 it('groups exact native bases and counts independent four-rarity sets',function()
  local result=vendor.review({normal,magic,rare,unique,normal,magic,rare,unique,normal})
  assert.equal(9,result.totalItems);assert.equal(1,#result.groups);local group=result.groups[1]
  assert.equal('Jade Amulet',group.base);assert.equal(2,group.sets);assert.equal(3,group.counts.NORMAL);assert.equal(2,group.counts.UNIQUE)
  assert.equal(9,group.items[9].index);assert.same({'MAGIC','RARE','UNIQUE'},group.missing);assert.equal(1,group.remaining.NORMAL);assert.matches('vendor offer',result.note,1,true)
 end)
 it('keeps other bases separate and reports missing rarities',function()
  local result=vendor.review({normal,rare,item('Normal','Amber Amulet')});assert.equal(2,#result.groups);local jade=result.groups[2];assert.equal('Jade Amulet',jade.base);assert.equal(0,jade.sets);assert.same({'MAGIC','UNIQUE'},jade.missing)
 end)
 it('rejects incomplete, unknown and mismatched copies',function()
  assert.has_error(function() vendor.parse('Rarity: Normal\nJade Amulet') end)
  assert.has_error(function() vendor.parse(item('Rare','Jade Amulet')) end)
  assert.has_error(function() vendor.parse(item('Normal','Imaginary Base')) end)
  assert.has_error(function() vendor.parse(item('Unique','Fake Name\nIron Hat')) end)
  assert.has_error(function() vendor.parse(item('Normal','Two-Toned Boots','Boots')..'\nUnidentified') end)
  assert.has_error(function() vendor.parse(item('Normal','Jade Amulet','Helmets')) end)
  assert.has_error(function() vendor.parse(item('Rare','^1Name\nJade Amulet')) end)
 end)
 it('handles a copied unidentified rare and normal CRLF text',function()
  assert.equal('Jade Amulet',vendor.parse(item('Rare','Jade Amulet')..'\nUnidentified').base)
  assert.equal('Jade Amulet',vendor.parse(normal:gsub('\n','\r\n')).base)
 end)
 it('accepts many items while bounding the total copied text',function()
  local copies={};for i=1,205 do copies[i]=normal end
  assert.equal(205,vendor.review(copies).totalItems)
  local long=normal..'\n'..string.rep('x',23000);local tooMany={};for i=1,184 do tooMany[i]=long end
  assert.has_error(function() vendor.review(tooMany) end)
 end)
 it('keeps Two-Toned Boots variants separate and rejects incomplete properties',function()
  local base=item('Normal','Two-Toned Boots','Boots')
  local armourEnergy=base..'\n--------\nArmour: 40\nEnergy Shield: 10'
  local armourEvasion=base..'\n--------\nArmour: 40\nEvasion Rating: 40'
  local evasionEnergy=base..'\n--------\nEvasion Rating: 40\nEnergy Shield: 10'
  assert.equal('Two-Toned Boots (Armour/Energy Shield)',vendor.parse(armourEnergy).base)
  assert.equal('Two-Toned Boots (Armour/Evasion)',vendor.parse(armourEvasion).base)
  assert.equal('Two-Toned Boots (Evasion/Energy Shield)',vendor.parse(evasionEnergy).base)
  assert.equal(3,#vendor.review({armourEnergy,armourEvasion,evasionEnergy}).groups)
  assert.has_error(function() vendor.parse(base..'\n--------\nArmour: 40') end)
 end)
end)

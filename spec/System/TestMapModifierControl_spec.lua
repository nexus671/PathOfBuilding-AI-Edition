describe("Map modifier explorer",function()
	before_each(function() newBuild();main.popups={} end)
	after_each(function() main.popups={} end)
	it("shows and retains observed effects, then clears them on tier changes",function()
		local observed={{kind="implicit",text="Area is Influenced by the Originator's Memories"},{kind="enchant",text="Players are Delirious"}}
		local initial={id="map-test",title="Map",patch="3.30.0.2.2",baseId="Metadata/Items/Maps/MapKeyTier5",tier=5,itemLevel=68,rarity="rare",selected={},observedEffects=observed}
		local captured;local controls=require("Classes.MapModifierControl").Open({initial=initial,keep=function(entry) captured=copyTable(entry);return "map-test" end})
		local text="";for _,row in ipairs(controls.affixes.list) do text=text..StripEscapes(row[1] or "").." " end
		assert.matches("Observed effects are not modeled",text);assert.matches("Players are Delirious",text)
		controls.keep:Click();assert.same(observed,captured.observedEffects)
		controls.tier:SelByValue(6,"val");controls.tier.selFunc();controls.keep:Click();assert.is_nil(captured.observedEffects)
	end)
	it("records and reopens map quality with documented effects",function()
		local captured;local controls=require("Classes.MapModifierControl").Open({keep=function(entry) captured=copyTable(entry);return "map-test" end})
		controls.quality:Click();local popup=main.popups[1].controls
		popup.kind:SetText("Pack Size");popup.value:SetText("20");popup.keep:Click()
		controls.keep:Click();assert.same({kind="Pack Size",value=20},captured.quality)
		captured.id="map-test";controls.close:Click()
		controls=require("Classes.MapModifierControl").Open({initial=captured,keep=function(entry) captured=copyTable(entry);return "map-test" end})
		local text="";for _,row in ipairs(controls.affixes.list) do text=text..StripEscapes(row[1] or "") end
		assert.matches("Quality %(Pack Size%): %+20%%",text);assert.matches("%+10%% Monster Pack Size",text)
		controls.quality:Click();popup=main.popups[1].controls;popup.clear:Click();controls.keep:Click();assert.is_nil(captured.quality)
	end)
	it("selects current map items and keeps their tier synchronized",function()
		local captured
		local controls=require("Classes.MapModifierControl").Open({keep=function(entry) captured=copyTable(entry);return "map-test" end})
		controls.keep:Click();assert.equal("Metadata/Items/Maps/MapKeyTier16",captured.baseId)
		controls.tier:SelByValue(5,"val");controls.tier.selFunc()
		controls.keep:Click();assert.equal("Metadata/Items/Maps/MapKeyTier5",captured.baseId);assert.equal(5,captured.tier)
		controls.base:Click();local picker=main.popups[1].controls
		picker.search:SetText("MapKeyTier11",true);assert.is_true(picker.choose:IsEnabled());picker.choose:Click()
		controls.keep:Click();assert.equal("Metadata/Items/Maps/MapKeyTier11",captured.baseId);assert.equal(11,captured.tier)
	end)
	it("browses and stages hypothetical modifiers without changing the build",function()
		local controls=require("Classes.MapModifierControl").Open()
		assert.is_true(#controls.list.list>0);assert.matches("not odds",controls.status.label)
		local first=controls.list.list[1];assert.is_truthy(first.entry)
		controls.list.onClick({line=first});assert.is_true(controls.add:IsEnabled())
		controls.add:Click();assert.is_true(controls.remove:IsEnabled())
		assert.is_true(#controls.affixes.list>0);assert.is_false(controls.add:IsEnabled())
		controls.remove:Click();assert.is_false(controls.remove:IsEnabled())
		assert.is_true(controls.next:IsEnabled());controls.next:Click();assert.is_true(controls.previous:IsEnabled())
		controls.previous:Click();assert.is_false(controls.previous:IsEnabled())
	end)
	it("resets pagination when switching maps and clears staged modifiers when the item level changes",function()
		local controls=require("Classes.MapModifierControl").Open()
		controls.next:Click();assert.matches("Page 2",controls.status.label)
		controls.base:Click()
		local picker=main.popups[1].controls
		picker.search:SetText("MapWorldsDunes",true);assert.is_true(picker.choose:IsEnabled());picker.choose:Click()
		assert.matches("Page 1",controls.status.label)
		controls.list.onClick({line=controls.list.list[1]});controls.add:Click()
		assert.is_true(controls.remove:IsEnabled())
		controls.level:SetText("68",true)
		assert.is_false(controls.remove:IsEnabled())
	end)
	it("switches rarity and clears staged modifiers",function()
		local controls=require("Classes.MapModifierControl").Open()
		controls.list.onClick({line=controls.list.list[1]});controls.add:Click();assert.is_true(controls.remove:IsEnabled())
		controls.rarity:SelByValue("magic","val");controls.rarity.selFunc()
		assert.is_false(controls.remove:IsEnabled())
		controls.search:SetText("MapContainsMirageWorlds",true);assert.matches("0 candidates",controls.status.label)
		controls.rarity:SelByValue("rare","val");controls.rarity.selFunc();assert.matches("1 candidates",controls.status.label)
	end)
	it("requires a valid item level and supported rarity before estimating",function()
		local controls=require("Classes.MapModifierControl").Open({build=build})
		controls.level:SetText("0",true);assert.is_falsy(controls.estimate:IsEnabled())
		controls.level:SetText("83",true);assert.is_true(controls.estimate:IsEnabled())
		controls.rarity:SelByValue("normal","val");controls.rarity.selFunc();assert.is_falsy(controls.estimate:IsEnabled())
	end)
	it("applies currency to a hypothetical map",function()
		local controls=require("Classes.MapModifierControl").Open()
		controls.rarity:SelByValue("normal","val");controls.rarity.selFunc()
		controls.currency:Click();local picker=main.popups[1].controls
		picker.search:SetText("Orb of Alchemy",true);picker.choose:Click()
		assert.equal("rare",controls.rarity:GetSelValueByKey("val"));assert.is_true(controls.remove:IsEnabled())
		assert.is_true(#controls.affixes.list>=4)
		local text="";for _,row in ipairs(controls.affixes.list) do text=text..StripEscapes(row[1] or "").."\n" end
		assert.matches("Modifier bonuses %(excludes quality%):",text);assert.matches("Atlas Drops",text);assert.matches("Pack size",text)
		controls.rarity:SelByValue("corrupted_rare","val");controls.rarity.selFunc();assert.is_true(controls.remove:IsEnabled())
	end)
	it("explains and disables currency actions unavailable for the current map",function()
		local controls=require("Classes.MapModifierControl").Open()
		controls.rarity:SelByValue("normal","val");controls.rarity.selFunc();controls.currency:Click()
		local picker=main.popups[1].controls;picker.search:SetText("Chaos Orb",true)
		assert.is_false(picker.choose:IsEnabled());local text="";for _,row in ipairs(picker.details.list) do text=text..StripEscapes(row[1] or "").." " end
		assert.matches("Requires a rare map",text)
		picker.search:SetText("Orb of Alchemy",true);assert.is_true(picker.choose:IsEnabled())
	end)
	it("keeps and reopens sampled values and removes them with their modifier",function()
		local captured;local controls=require("Classes.MapModifierControl").Open({keep=function(entry) captured=copyTable(entry);return "map-test" end})
		controls.rarity:SelByValue("normal","val");controls.rarity.selFunc();controls.currency:Click()
		local picker=main.popups[1].controls;picker.search:SetText("Orb of Alchemy",true);picker.choose:Click();controls.keep:Click()
		assert.equal(#captured.selected,#captured.rolls);captured.id="map-test";controls.close:Click()
		controls=require("Classes.MapModifierControl").Open({initial=captured,keep=function(entry) captured=copyTable(entry);return "map-test" end})
		controls.remove:Click();controls.keep:Click();assert.equal(#captured.selected,#captured.rolls)
	end)
	it("keeps and reopens estimate targets with the map draft",function()
		local captured;local controls=require("Classes.MapModifierControl").Open({build=build,keep=function(entry) captured=copyTable(entry);return "map-test" end})
		controls.estimate:Click();local estimate=main.popups[1].controls;estimate.addAvoid:Click()
		local picker=main.popups[1].controls;picker.search:SetText("MapContainsMirageWorlds",true);picker.choose:Click()
		estimate.keepSettings:Click();estimate.close:Click();controls.keep:Click()
		assert.same({"MapContainsMirageWorlds"},captured.estimate.avoid);captured.id="map-test";controls.close:Click()
		controls=require("Classes.MapModifierControl").Open({build=build,initial=captured,keep=function(entry) captured=copyTable(entry);return "map-test" end});controls.estimate:Click()
		estimate=main.popups[1].controls;local text="";for _,line in ipairs(estimate.avoid.list) do text=text..StripEscapes(line[1] or "") end
		assert.matches("Mirage",text);estimate.close:Click();controls.level:SetText("68",true);controls.keep:Click();assert.is_nil(captured.estimate)
	end)
	it("keeps and reopens a corrupted nine-modifier map",function()
		local captured;local controls=require("Classes.MapModifierControl").Open({build=build,keep=function(entry) captured=copyTable(entry);return "corrupt-map" end})
		controls.list.onClick({line=controls.list.list[1]});controls.add:Click()
		controls.rarity:SelByValue("corrupted_rare","val");controls.rarity.selFunc()
		assert.is_true(controls.remove:IsEnabled());controls.remove:Click()
		assert.is_false(controls.currency:IsEnabled());assert.is_false(controls.estimate:IsEnabled())
		for _=1,9 do assert.is_truthy(controls.list.list[1].entry);controls.list.onClick({line=controls.list.list[1]});controls.add:Click() end
		controls.keep:Click();assert.is_true(captured.corrupted);assert.equal(9,#captured.selected);captured.id="corrupt-map";controls.close:Click()
		controls=require("Classes.MapModifierControl").Open({build=build,initial=captured,keep=function(entry) captured=copyTable(entry);return "corrupt-map" end})
		assert.equal("corrupted_rare",controls.rarity:GetSelValueByKey("val"));assert.is_false(controls.currency:IsEnabled());controls.keep:Click();assert.equal(9,#captured.selected)
	end)

	it("records and reopens a corruption implicit and exact value",function()
		local captured;local controls=require("Classes.MapModifierControl").Open({keep=function(entry) captured=copyTable(entry);return "map-implicit" end})
		controls.rarity:SelByValue("corrupted_rare","val");controls.rarity.selFunc();controls.implicit:Click()
		local popup=main.popups[1].controls;popup.choice:SelByValue("MapCorruptionItemRarity","val");popup.choice.selFunc();popup.value:SetText("15",true);popup.keep:Click()
		local lines="";for _,row in ipairs(controls.affixes.list) do lines=lines..StripEscapes(row[1] or "") end;assert.matches("15%% Item Rarity",lines)
		controls.keep:Click();assert.same({id="MapCorruptionItemRarity",value=15},captured.implicit);captured.id="map-implicit";controls.close:Click()
		controls=require("Classes.MapModifierControl").Open({initial=captured,keep=function(entry) captured=copyTable(entry);return "map-implicit" end});controls.implicit:Click()
		popup=main.popups[1].controls;assert.equal("MapCorruptionItemRarity",popup.choice:GetSelValueByKey("val"));assert.equal("15",popup.value.buf)
	end)

end)

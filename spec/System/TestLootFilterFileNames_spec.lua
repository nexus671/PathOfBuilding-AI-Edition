describe("Mode-specific filter files",function()
	local names=require("Modules.LootFilterFileNames")
	it("selects and validates the extension for each mode",function()
		local normal={mode="Normal"};local ruthless={mode="Ruthless"}
		assert.equal(".filter",names.extension(normal));assert.equal(".ruthlessfilter",names.extension(ruthless))
		assert.equal("My-plan-3.filter",names.variant(normal,"My-plan.filter",3))
		assert.equal("My-plan-3.ruthlessfilter",names.variant(ruthless,"My-plan.ruthlessfilter",3))
		assert.has_error(function() names.stem(ruthless,"My-plan.filter") end)
		assert.has_error(function() names.stem(normal,"../outside.filter") end)
		assert.is_true(names.isFilter("MY.RUTHLESSFILTER"));assert.is_false(names.isFilter(".ruthlessfilter"))
	end)
	it("loads a referenced Ruthless sibling without following path references",function()
		local path=os.tmpname()..".ruthlessfilter";local name=path:match("([^/\\]+)$")
		local file=assert(io.open(path,"wb"));file:write("Minimal\n BaseType \"Iron Hat\"");file:close()
		local ok,result=pcall(require("Modules.LootFilterImports").collectLocal,'Import "'..name..'"\nImport "../outside.ruthlessfilter"',path)
		os.remove(path);assert.is_true(ok);assert.equal(1,#result.files);assert.equal(name,result.files[1].name);assert.equal(1,#result.issues)
	end)
end)

describe("Crafting starting-item property inheritance",function()
	local sim=require("Modules.CraftingSimulator")
	before_each(function() newBuild() end)
	it("keeps copied influence unless explicitly cleared",function()
		local base="Rarity: NORMAL\nGlorious Plate\nItem Level: 86";local model=sim.model(base)
		local rare=copyTable(model.initial);rare.rarity="RARE"
		local influenced=sim.perform(base,{method="influence_exalt",influence="shaper"},43,rare)
		local imported=sim.model(influenced.itemText);assert.same({"shaper"},imported.initial.influences)
		local partial={rarity="RARE",affixes=copyTable(imported.initial.affixes)}
		local state=sim.validateState(imported,partial);assert.same({"shaper"},state.influences);assert.is_nil(partial.influences)
		assert.has_error(function() sim.perform(influenced.itemText,{method="influence_exalt",influence="elder"},1,partial) end)
		partial.influences={};partial.affixes={};assert.same({},sim.validateState(imported,partial).influences)
	end)
	it("keeps memory strands and honours an explicit zero",function()
		local raw="Rarity: NORMAL\nGlorious Plate\nItem Level: 86\nMemory Strands: 82";local model=sim.model(raw)
		local partial={rarity="NORMAL",affixes={}};assert.equal(82,sim.validateState(model,partial).memoryStrands)
		local complete=sim.perform(raw,{method="alchemy"},77);local supplied=sim.perform(raw,{method="alchemy"},77,partial)
		assert.equal(complete.state.memoryStrands,supplied.state.memoryStrands);assert.same(complete.state.affixes,supplied.state.affixes)
		partial.memoryStrands=0;assert.equal(0,sim.validateState(model,partial).memoryStrands)
	end)
	it("preserves copied catalyst quality unless explicitly replaced",function()
		local raw="Rarity: NORMAL\nCoral Ring\nItem Level: 86\nCatalyst: Fertile\nCatalystQuality: 20\nImplicits: 1\n+36 to maximum Life"
		local model=sim.model(raw);local partial={rarity="NORMAL",affixes={}};local state=sim.validateState(model,partial)
		assert.equal(model.initial.catalyst,state.catalyst);assert.equal(20,state.catalystQuality)
		assert.has_error(function() sim.perform(raw,{method="catalyst",catalyst=model.initial.catalyst},1,partial) end)
		partial.catalyst=model.initial.catalyst;partial.catalystQuality=0
		assert.equal(0,sim.validateState(model,partial).catalystQuality)
		partial.catalyst=5;partial.catalystQuality=nil
		local changed=sim.validateState(model,partial);assert.equal(5,changed.catalyst);assert.is_nil(changed.catalystQuality)
	end)
	it("uses PoB's default 20% for a named catalyst with no quality line",function()
		local raw="Rarity: NORMAL\nRuby Ring\nItem Level: 86\nCatalyst: Prismatic\nImplicits: 1\n{tags:resistance}+25% to Fire Resistance"
		local model=sim.model(raw);assert.is_nil(model.item.catalystQuality);assert.equal(20,model.initial.catalystQuality)
		assert.equal(30,model.item.baseModList:Sum("BASE",nil,"FireResist"));assert.equal(30,sim.toItem(model,model.initial).baseModList:Sum("BASE",nil,"FireResist"))
		assert.is_true(sim.matches(model.initial,{},"NORMAL",model,{catalyst=8,minCatalystQuality=20}));assert.has_error(function() sim.perform(raw,{method="catalyst",catalyst=8},42) end)
		local partial={rarity="NORMAL",affixes={}};local inherited=sim.validateState(model,partial);assert.equal(20,inherited.catalystQuality);assert.is_nil(partial.catalystQuality)
		local output=sim.itemText(model,model.initial);assert.matches("CatalystQuality: 20",output,1,true);assert.equal(20,sim.model(output).initial.catalystQuality)
		local zero=raw:gsub("Catalyst: Prismatic","Catalyst: Prismatic\nCatalystQuality: 0");local zeroModel=sim.model(zero);assert.equal(0,zeroModel.initial.catalystQuality);assert.is_false(sim.matches(zeroModel.initial,{},"NORMAL",zeroModel,{catalyst=8,minCatalystQuality=20}));assert.is_true(sim.perform(zero,{method="catalyst",catalyst=8},42).state.catalystQuality>0)
		local swapped=sim.perform(raw,{method="catalyst",catalyst=4},42);assert.equal(4,swapped.state.catalyst);assert.is_true(swapped.state.catalystQuality<20)
	end)
	it("retains a copied Eldritch implicit when adding the other side",function()
		local raw="Rarity: NORMAL\nPlate Vest\nItem Level: 86"
		local first=sim.perform(raw,{method="eldritch_implicit",side="Exarch",tier=2},11)
		local model=sim.model(first.itemText);assert.same(first.state.implicits,model.initial.implicits)
		local partial={rarity="NORMAL",affixes={}};local state=sim.validateState(model,partial)
		assert.same(model.initial.implicits,state.implicits);assert.is_nil(partial.implicits)
		local second=sim.perform(first.itemText,{method="eldritch_implicit",side="Eater",tier=1},12,partial)
		assert.equal(2,#second.state.implicits);assert.equal(first.state.implicits[1].id,second.state.implicits[1].id)
		partial.implicits={};assert.same({},sim.validateState(model,partial).implicits)
		local forged=first.itemText:gsub("crafting_"..first.state.implicits[1].id,"crafting_InvalidModifier")
		local unknown=sim.model(forged);assert.is_true(unknown.unresolvedEldritch)
		assert.is_nil(sim.validateState(unknown,{rarity="NORMAL",affixes={}}).implicits)
		assert.has_error(function() sim.perform(forged,{method="eldritch_implicit",side="Eater",tier=1},12,{rarity="NORMAL",affixes={}}) end)
	end)
	it("retains both known Eldritch and corruption implicits in a partial state",function()
		local raw="Rarity: NORMAL\nPlate Vest\nItem Level: 86";local model=sim.model(raw)
		local first=sim.perform(raw,{method="eldritch_implicit",side="Exarch",tier=2},11).state
		local both=sim.perform(raw,{method="eldritch_implicit",side="Eater",tier=1},12,first).state
		local mixed=sim.action(model,both,{method="vaal"},function() return 0 end)
		local item=sim.toItem(model,mixed);local imported=sim.model(item.raw)
		assert.equal(1,#imported.initial.implicits);assert.equal(1,#imported.initial.corruptedImplicits)
		local state=sim.validateState(imported,{rarity="NORMAL",affixes={}})
		assert.same(imported.initial.implicits,state.implicits);assert.same(imported.initial.corruptedImplicits,state.corruptedImplicits)
		local hypothetical=sim.validateState(imported,{rarity="NORMAL",affixes={},corrupted=false})
		assert.same(imported.initial.implicits,hypothetical.implicits);assert.is_nil(hypothetical.corruptedImplicits)
		local replacement=sim.validateState(imported,{rarity="NORMAL",affixes={},corrupted=true,corruptedImplicits=copyTable(imported.initial.corruptedImplicits)})
		assert.is_nil(replacement.implicits);assert.same(imported.initial.corruptedImplicits,replacement.corruptedImplicits)
	end)
end)

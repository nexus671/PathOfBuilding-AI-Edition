describe("Same-name rare vendor review",function()
 local vendor=require("Modules.VendorRarePairs")
 local function item(name,base) return "Item Class: Helmets\nRarity: Rare\n"..name.."\n"..(base or "Iron Hat").."\n--------\nItem Level: 80" end
 it("groups exact names and prioritises triples without using an item twice",function()
  local a=item("Vortex Visage");local b=item("Vortex Visage","Hubris Circlet");local c=item("Doom Dome")
  local result=vendor.review({a,b,a,b,a,c});assert.equal(6,result.totalItems);assert.equal("Vortex Visage",result.groups[1].name)
  assert.equal(5,result.groups[1].count);assert.equal(1,result.groups[1].exalted);assert.equal(1,result.groups[1].chaos);assert.equal(0,result.groups[1].remaining)
  assert.equal("Hubris Circlet",result.groups[1].items[2].base);assert.equal(1,result.groups[2].remaining)
  assert.matches("each paste",result.note)
 end)
 it("does not impose an item-count limit",function()
  local copies={};for i=1,205 do copies[i]=item("Vortex Visage") end
  local result=vendor.review(copies);assert.equal(205,result.totalItems);assert.equal(68,result.groups[1].exalted);assert.equal(1,result.groups[1].remaining)
 end)
 it("bounds total copied text without limiting item count",function()
  local raw=item("Vortex Visage").."\n"..string.rep("x",23000);local copies={};for i=1,184 do copies[i]=raw end
  assert.has_error(function() vendor.review(copies) end)
 end)
 it("rejects unknown, unidentified, malformed and non-rare items",function()
  assert.has_error(function() vendor.parse("Rarity: Normal\nIron Hat") end)
  assert.has_error(function() vendor.parse("Rarity: Rare\nIron Hat\n--------\nUnidentified") end)
  assert.has_error(function() vendor.parse("Rarity: Rare\n^1Fake\nIron Hat") end)
  assert.has_error(function() vendor.review({item("Vortex Visage"),"Rarity: Magic\nIron Hat"}) end)
 end)
 it("keeps different names separate and handles CRLF",function()
  local first=item("Vortex Visage"):gsub("\n","\r\n")
  local result=vendor.review({first,item("Vortex Crown")});assert.equal(2,#result.groups);assert.equal(0,result.groups[1].chaos)
 end)
end)

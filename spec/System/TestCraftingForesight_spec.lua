describe("Experimental Hinekora planning",function()
 local sim=require("Modules.CraftingSimulator")
 local raw="Rarity: RARE\nExample\nIron Hat\nItem Level: 86"
 before_each(function() newBuild() end)
 it("models both Lock sources and a foreseeing target",function()
  local model=sim.model(raw);local before=copyTable(model.initial)
  local locked=sim.action(model,before,{method="hinekora_lock"},function() return 0.25 end)
  assert.is_true(locked.foreseeing);assert.is_nil(before.foreseeing)
  assert.equal(1,sim.components({method="hinekora_lock"})["Metadata/Items/Currency/CurrencyHinekorasLock"])
  local odds=sim.calculate(raw,{method="gwennen",firstOutcome=1002,secondOutcome=1000},{},nil,{requirements={foreseeing=true},trials=1})
  assert.is_false(odds.sampled);assert.equal(50,odds.successChance)
  local result=sim.simulate(raw,{steps={{method="hinekora_lock"}},targets={},requirements={foreseeing=true}},{trials=1,maxActions=1,currency="chaos",prices={hinekora_lock=5}})
  assert.equal(100,result.successChance);assert.equal(5,result.meanCost)
 end)
 it("keeps hypothetical samples reproducible and clears the marker on a craft",function()
  local model=sim.model(raw);local locked=sim.action(model,model.initial,{method="gwennen",firstOutcome=1002,secondOutcome=1000},function() return 0.25 end)
  local before=copyTable(locked);local a=sim.perform(raw,{method="chaos"},123,locked);local b=sim.perform(raw,{method="chaos"},123,locked)
  assert.same(a.state,b.state);assert.same(before,locked);assert.is_nil(a.state.foreseeing)
  local warned=false;for _,warning in ipairs(a.warnings) do if warning.code=="foreseeing_sample" then warned=true end end;assert.is_true(warned)
  local bad=copyTable(locked);bad.corrupted=true;assert.has_error(function() sim.validateState(model,bad) end)
  assert.has_error(function() sim.validateRecipe({steps={{method="chaos"}},targets={},requirements={foreseeing=true,mirrored=true}}) end)
 end)
end)
